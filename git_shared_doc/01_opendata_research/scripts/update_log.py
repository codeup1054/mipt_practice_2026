def main() -> None:
    d = json.loads(LOG.read_text(encoding="utf-8"))
    sections = d["sections"]

    sections[:] = [s for s in sections if s.get("id") != "t1-data"]
    idx = next((i for i, s in enumerate(sections) if s.get("id") == "t1-answers"), None)
    if idx is None:
        sections.append(SECTION)
    else:
        sections.insert(idx + 1, SECTION)

    # timeline: новая запись первой
    log = next(s for s in sections if s.get("id") == "log")
    tl = next(b for b in log["blocks"] if b.get("type") == "timeline")
    tl["items"] = [i for i in tl["items"]
                   if i.get("title") != TIMELINE["title"]]
    tl["items"].insert(0, TIMELINE)

    version = float(d["meta"].get("version", "0.96"))
    d["meta"]["version"] = f"{version + 0.01:.2f}"
    d["meta"]["updated"] = "2026-11-23T18:20"

    LOG.write_text(json.dumps(d, ensure_ascii=False, indent=2) + "\n",
                   encoding="utf-8")
    print(f"t1-data вставлена после t1-answers (индекс {idx}); "
          f"версия {d['meta']['version']}")


if __name__ == "__main__":
    main()
